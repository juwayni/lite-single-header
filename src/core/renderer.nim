proc drawString*(buf: ImageBuffer, text: string, startX, startY: float, color: Color, clip: Rect) =
  var curX = startX
  for ch in text:
    let asciiVal = ord(ch)
    if asciiVal >= 0 and asciiVal < 128:
      let bitmap = fontBitmaps[asciiVal]
      for row in 0 ..< 12:
        let lineVal = bitmap[row]
        for col in 0 ..< 8:
          if (lineVal and (0x80u8 shr col)) != 0u8:
            buf.setPixel(int(curX) + col, int(startY) + row, color, clip)
    curX += 8.0

proc renderFrameToBuffer*(w, h: int): ImageBuffer =
  let buf = newImageBuffer(w, h, color("#252529"))
  var clip = initRect(0.0, 0.0, float(w), float(h))

  for cmd in drawCommands:
    case cmd.commandType
    of rcSetClip:
      clip = cmd.rect
    of rcDrawRect:
      buf.fillRect(cmd.rect, cmd.color, clip)
    of rcDrawText:
      buf.drawString(cmd.text, cmd.rect.x, cmd.rect.y, cmd.color, clip)

  return buf

proc savePPM*(buf: ImageBuffer, filepath: string) =
  var f = open(filepath, fmWrite)
  f.writeLine("P3")
  f.writeLine($buf.width & " " & $buf.height)
  f.writeLine("255")
  for i in 0 ..< buf.pixels.len:
    let px = buf.pixels[i]
    f.writeLine($int(px.r) & " " & $int(px.g) & " " & $int(px.b))
  f.close()
