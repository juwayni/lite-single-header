## renderer.nim - Rendering backend primitives, software rasterizer, and drawing commands
## Ports lite renderer/rencache C API to Nim with software rasterization support.

import common, style

type
  RenderCommandType* = enum
    rcSetClip, rcDrawRect, rcDrawText

  RenderCommand* = object
    commandType*: RenderCommandType
    rect*: Rect
    color*: Color
    text*: string
    font*: FontHandle

  ImageBuffer* = ref object
    width*, height*: int
    pixels*: seq[Color]

var drawCommands*: seq[RenderCommand] = @[]
var currentClip*: Rect = initRect(0, 0, 1280, 720)

proc beginFrame*() =
  drawCommands = @[]

proc endFrame*() =
  discard

proc setClipRect*(rect: Rect) =
  currentClip = rect
  drawCommands.add(RenderCommand(commandType: rcSetClip, rect: rect))

proc drawRect*(rect: Rect, color: Color) =
  drawCommands.add(RenderCommand(commandType: rcDrawRect, rect: rect, color: color))

proc getFontHeight*(font: FontHandle): float =
  if font != nil and font.size > 0:
    return font.size
  return 14.0

proc getCharWidth*(font: FontHandle, ch: char): float =
  if font != nil and font.size > 0:
    return font.size * 0.6
  return 8.0

proc getTextWidth*(font: FontHandle, text: string): float =
  let charW = getCharWidth(font, 'a')
  return float(text.len) * charW

proc drawText*(font: FontHandle, text: string, x, y: float, color: Color): float =
  let width = getTextWidth(font, text)
  drawCommands.add(RenderCommand(
    commandType: rcDrawText,
    rect: initRect(x, y, width, getFontHeight(font)),
    color: color,
    text: text,
    font: font
  ))
  return x + width

# Software Rasterizer Implementation
proc newImageBuffer*(w, h: int, bg: Color = color("#252529")): ImageBuffer =
  let buf = ImageBuffer(width: w, height: h, pixels: newSeq[Color](w * h))
  for i in 0 ..< w * h:
    buf.pixels[i] = bg
  return buf

proc setPixel*(buf: ImageBuffer, x, y: int, color: Color, clip: Rect) =
  if x < 0 or y < 0 or x >= buf.width or y >= buf.height: return
  if float(x) < clip.x or float(y) < clip.y or float(x) >= clip.x + clip.width or float(y) >= clip.y + clip.height: return

  let idx = y * buf.width + x
  if color.a >= 255.0:
    buf.pixels[idx] = color
  elif color.a > 0.0:
    let dst = buf.pixels[idx]
    let alpha = color.a / 255.0
    let inv = 1.0 - alpha
    let rVal = clamp(color.r * alpha + dst.r * inv, 0.0, 255.0)
    let gVal = clamp(color.g * alpha + dst.g * inv, 0.0, 255.0)
    let bVal = clamp(color.b * alpha + dst.b * inv, 0.0, 255.0)
    buf.pixels[idx] = initColor(rVal, gVal, bVal, 255.0)

proc fillRect*(buf: ImageBuffer, rect: Rect, color: Color, clip: Rect) =
  let x1 = int(max(0.0, rect.x))
  let y1 = int(max(0.0, rect.y))
  let x2 = int(min(float(buf.width), rect.x + rect.width))
  let y2 = int(min(float(buf.height), rect.y + rect.height))
  for y in y1 ..< y2:
    for x in x1 ..< x2:
      buf.setPixel(x, y, color, clip)

